// Regenerates the API contract (ARCH-01): builds the API, writes openapi.json
// from the compiled controllers and derives src/schema.d.ts from it.
// `--check` generates into a temporary directory and fails if the committed
// files differ, so a changed response or DTO cannot ship without its contract.
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const packageDirectory = join(dirname(fileURLToPath(import.meta.url)), "..");
const apiDirectory = join(packageDirectory, "../../apps/api");
const check = process.argv.includes("--check");
const committed = {
  document: join(packageDirectory, "openapi.json"),
  types: join(packageDirectory, "src/schema.d.ts"),
};

// Its own output directory: never replaces dist/ of a running `pnpm dev` or build.
run("pnpm", ["exec", "nest", "build", "--path", "tsconfig.contract.json"], apiDirectory);
run(
  "node",
  [join(packageDirectory, "scripts/check-documented-fields.cjs"), "dist/contract/src"],
  apiDirectory,
);
const output = check ? mkdtempSync(join(tmpdir(), "api-contract-")) : null;
const target = output
  ? { document: join(output, "openapi.json"), types: join(output, "schema.d.ts") }
  : committed;
try {
  run("node", ["dist/contract/src/openapi/generate-openapi.js", target.document], apiDirectory);
  writeFileSync(target.types, await generateTypes(target.document));
  if (check) {
    const stale = Object.keys(committed).filter(
      (key) => read(committed[key]) !== read(target[key]),
    );
    if (stale.length > 0) {
      console.error(
        "The API contract is out of date: run `pnpm api:contract` and commit packages/api-contract.",
      );
      process.exitCode = 1;
    } else {
      console.log("The API contract matches the API.");
    }
  }
} finally {
  if (output) rmSync(output, { recursive: true, force: true });
}

/** Uploaded and downloaded files (`format: binary`) are Blobs in the browser, not strings. */
async function generateTypes(document) {
  const blob = ts.factory.createTypeReferenceNode("Blob");
  const ast = await openapiTS(pathToFileURL(document), {
    transform(schema) {
      if (schema.format !== "binary") return undefined;
      return schema.nullable
        ? ts.factory.createUnionTypeNode([
            blob,
            ts.factory.createLiteralTypeNode(ts.factory.createNull()),
          ])
        : blob;
    },
  });
  return `/**
 * This file was auto-generated by openapi-typescript (scripts/generate.mjs).
 * Do not make direct changes to the file.
 */

${astToString(ast)}`;
}

function read(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, stdio: ["ignore", "ignore", "inherit"] });
  if (result.status !== 0) throw new Error(`${command} ${args.join(" ")} failed.`);
}
